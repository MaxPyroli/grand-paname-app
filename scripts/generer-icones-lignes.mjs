// Génère app/ligneIcons.ts : les symboles de lignes (app/icons/lignes/*.svg) allégés avec svgo et
// encodés en « data URI », comme app/modeIcons.ts, pour être affichés avec expo-image.
//
// Usage (depuis la racine du dépôt) :  node scripts/generer-icones-lignes.mjs
//
// Sources : app/icons/lignes/<mode>-<ligne>.svg, plus <mode>-<ligne>-fonce.svg pour les symboles qui ont
// une version « support foncé » (tram, câble : leur texte noir sur fond transparent serait invisible en mode sombre).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const racine = path.resolve(import.meta.dirname, '..');
const dossier = path.join(racine, 'app', 'icons', 'lignes');
const sortie = path.join(racine, 'app', 'ligneIcons.ts');
// svgo est une dépendance indirecte de l'application (transformateur SVG de Metro).
const { optimize } = createRequire(path.join(racine, 'app', 'package.json'))('svgo');

function alleger(svg) {
  // Les exports Illustrator découpent le dessin avec un rectangle égal à la page : inutile, et fragile
  // pour les lecteurs SVG simples. On l'enlève avant d'optimiser.
  const brut = svg
    .replace(/<clipPath[\s\S]*?<\/clipPath>/g, '')
    .replace(/clip-path:\s*url\([^)]*\);?/g, '')
    .replace(/\sclip-path="url\([^"]*\)"/g, '');
  return optimize(brut, {
    multipass: true,
    plugins: [{ name: 'preset-default', params: { overrides: { inlineStyles: { onlyMatchedOnce: false }, removeViewBox: false } } }],
  }).data;
}

const fichiers = fs.readdirSync(dossier).filter(f => f.endsWith('.svg')).sort();
const lignes = [];
let avant = 0, apres = 0;
for (const f of fichiers) {
  const source = fs.readFileSync(path.join(dossier, f), 'utf8');
  const leger = alleger(source);
  avant += Buffer.byteLength(source);
  apres += Buffer.byteLength(leger);
  lignes.push(`  '${f.replace(/\.svg$/, '')}': "data:image/svg+xml;base64,${Buffer.from(leger).toString('base64')}",`);
}

fs.writeFileSync(sortie,
  '// Auto-generated by scripts/generer-icones-lignes.mjs — do not edit by hand\n'
  + 'export const LIGNE_ICONS: Record<string, string> = {\n' + lignes.join('\n') + '\n};\n');
console.log(`${fichiers.length} symboles, ${(avant / 1024).toFixed(0)} Ko → ${(apres / 1024).toFixed(0)} Ko (${path.relative(racine, sortie)})`);
